"""Write catalog.inc from catalog.json, the Apple bitmap catalog of the themes
repository: the bank's base and file offset, each bitmap's offset in the bank
with its padding in the low two bits, the low 16 bits of each stock checksum,
the catalog fingerprint, and the indices of the assets the extension treats
specially.

    python3 tools/catalog_inc.py catalog.json build/catalog.inc
    python3 tools/catalog_inc.py catalog.json --check build/classic.rvt

The second form checks that a theme file carries the catalog's fingerprint.
"""

import json
import sys
from pathlib import Path

# Stock blue artwork and the role it is recoloured with. Blue that marks content
# (capacity legends, playlist kinds) is not listed.
ACCENT_ART = {
    "RVT_ROLE_SELECTION": (
        "OptionBar_White_Thumb_LeftCap_Image",
        "OptionBar_White_Thumb_Center_Image",
        "OptionBar_White_Thumb_RightCap_Image",
        "OptionBar_Black_Thumb_LeftCap_Image",
        "OptionBar_Black_Thumb_Center_Image",
        "OptionBar_Black_Thumb_RightCap_Image",
        "System_ActiveButtonLeftCap_Image",
        "System_ActiveButtonRightCap_Image",
        "System_ActiveButtonFill_Image",
        "DateTimePicker_Selection",
        "Alarms_Timer_Time_Panel_Focus",
        "Settings_DateTime_Capsule_Hilite",
        "Calendar_Hilite_Cell",
        "LockScreen_TumblerFocus_Image",
        "Settings_MainMenu_CheckmarkWhite_Image",
    ),
    "RVT_ROLE_ACCENT_FILL": (
        "NowPlaying_ProgressBar_Active_Fill_Image",
        "NowPlaying_ProgressBar_Scrub_Image",
        "Genius_Slider_Endcap_Image",
        "Genius_Slider_Fill_Image",
        "Podcasts_new_item_Image",
        "Podcasts_new_item_video_Image",
        "NowPlaying_Blue_Dot_Image",
        "NowPlaying_Blue_Star_Image",
        "NowPlaying_Large_Blue_Star_Image",
        "StatusBarWhite_PlayStatus_Image",
        "NowPlaying_White_Play_Image",
        "NowPlaying_White_Pause_Image",
        "NowPlaying_White_FF_Image",
        "NowPlaying_White_Rew_Image",
        "Radio_Preset_Image",
        "Radio_Signal_Indicator_Light_Image",
    ),
}
RECOLORABLE_FORMATS = (0x64, 0x65, 0x1888)

# Stock labels drawn in a fixed colour over art a theme may replace, by the
# first view of a run of consecutive ids, the run's length and the asset behind
# them: they take the text or background role, whichever contrasts more with
# that art.
CONTRAST_TEXT = (
    ("RES_NowPlaying_StatusBar_Text_View", 1, "NowPlaying_StatusBar_Image"),
    ("RES_LockScreen_TumblerDigit0_View", 4, "LockScreen_TumblerBgnd_Image"),
    ("RES_VolumeLimitLockScreen_TumblerDigit0_View", 4, "LockScreen_TumblerBgnd_Image"),
    ("RES_DateTimePicker_Value1", 3, "DateTimePicker_Well"),
    ("RES_CoverFlow_Backside_AlbumTitle_Text", 2, "CoverFlow_Backside_Top_Image"),
)
WELLS = (
    "OptionBar_White_Well_Center_Image",
    "OptionBar_Black_Well_Center_Image",
    "OptionBar_NowPlaying_Well_Center_Image",
)
FIELD = "System_Input_Field_Middle_Image"
CELLS = ("Calendar_Active_Cell", "Calendar_Inactive_Cell", "Calendar_Hilite_Cell")
FINGERPRINT_AT = 8
FINGERPRINT_BYTES = 8


def check(catalog, rvt):
    stored = bytes.fromhex(catalog["fingerprint"])
    found = rvt.read_bytes()[FINGERPRINT_AT : FINGERPRINT_AT + FINGERPRINT_BYTES]
    if found != stored:
        raise SystemExit(f"{rvt} was compiled against another catalog")


def write(catalog, out):
    bitmaps = sorted(catalog["bitmaps"], key=lambda b: b["address"])
    index = {b["name"]: i for i, b in enumerate(bitmaps)}
    if len(index) != len(bitmaps):
        raise SystemExit("catalog names are not unique")
    base = bitmaps[0]["address"]
    if base % 4 or bitmaps[0]["offset"] % 4:
        raise SystemExit("the bank does not start on a word")
    at = base
    offsets = []
    for b in bitmaps:
        if b["address"] != at:
            raise SystemExit(f"{b['name']} does not follow the previous bitmap")
        padding = -b["bytes"] & 3
        offsets.append(at - base | padding)
        at += b["bytes"] + padding
    offsets.append(at - base)
    for name in ACCENT_ART["RVT_ROLE_SELECTION"] + ACCENT_ART["RVT_ROLE_ACCENT_FILL"]:
        if bitmaps[index[name]]["format"] not in RECOLORABLE_FORMATS:
            raise SystemExit(f"{name} is not paletted or ARGB")
    digest = bytes.fromhex(catalog["fingerprint"])
    lines = [
        "/* Generated by tools/catalog_inc.py from catalog.json; do not edit. */",
        f"#define CATALOG_COUNT {len(bitmaps)}",
        f"#define CATALOG_BASE {base:#x}u /* first bitmap in RAM */",
        f"#define CATALOG_FILE_OFFSET {bitmaps[0]['offset']:#x}u"
        " /* the same in the firmware file */",
        f"#define CATALOG_BANK_BYTES {at - base}u",
        "static const uint8_t fingerprint[RVT_FINGERPRINT_BYTES] = {"
        + ", ".join(f"{b:#04x}" for b in digest)
        + "};",
        "static const uint32_t catalog_offsets[CATALOG_COUNT + 1] = {",
        *(f"    {o}u," for o in offsets),
        "};",
        "static const uint16_t catalog_crcs[CATALOG_COUNT] = {",
        *(f"    {b['crc32'] & 0xFFFF:#06x}," for b in bitmaps),
        "};",
        "static const uint16_t well_centers[3] = {"
        + ", ".join(str(index[n]) for n in WELLS)
        + "};",
        f"static const uint16_t field_center = {index[FIELD]};",
        "static const uint16_t calendar_cells[3] = {"
        + ", ".join(str(index[n]) for n in CELLS)
        + "};",
        "static const struct contrast_text contrast_text[] = {",
        *(
            f"    {{{first}, {count}, {index[name]}}},"
            for first, count, name in CONTRAST_TEXT
        ),
        "};",
        "static const struct accent_art accent_art[] = {",
        *(
            f"    {{{index[name]}, {role}}},"
            for role, names in ACCENT_ART.items()
            for name in names
        ),
        "};",
        "",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))


def main():
    catalog = json.loads(Path(sys.argv[1]).read_text())
    if sys.argv[2] == "--check":
        check(catalog, Path(sys.argv[3]))
    else:
        write(catalog, Path(sys.argv[2]))


if __name__ == "__main__":
    main()
